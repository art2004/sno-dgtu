def fmt_version(v: str) -> str:
    try:
        return datetime.fromisoformat(v).strftime("%d.%m.%Y")
    except (TypeError, ValueError):
        return str(v)


def fmt_consent_at(value: Any) -> str:
    """«08.10.2026 14:05» из ISO-времени согласия (МСК)."""
    if not value:
        return ""
    try:
        return datetime.fromisoformat(str(value)).strftime("%d.%m.%Y %H:%M")
    except ValueError:
        return str(value)


def has_consent(user: Optional[dict]) -> bool:
    """Есть согласие на текущую версию политики (user - строка users из БД)."""
    return bool(user and user.get("pd_consent_at") and user.get("pd_consent_version") == POLICY_VERSION)


def needs_consent(user_id: int, db_path: Any = None) -> bool:
    """Пользователя нужно попросить о согласии (нет его или оно на старую версию политики).
    Кэш чтения db сбрасывается любой записью этого процесса (в т.ч. set_pd_consent / clear_pd_consent),
    так что лишнего запроса к БД на каждом клике нет."""
    import db

    user = db.get_user_by_id(int(user_id), db_path=db_path)
    return user is not None and not has_consent(user)


def give_consent(user: dict, checked: bool, db_path: Any = None, log: bool = True) -> tuple[bool, str]:
    """Кнопка «Продолжить»: без галочки - отказ; с галочкой - запись времени и версии в БД (+ журнал)."""
    import db

    if not checked:
        return False, "Чтобы продолжить, отметьте согласие на обработку персональных данных."
    ts = db.set_pd_consent(user["id"], POLICY_VERSION, db_path)
    if log:
        import audit

        audit.log("pd_consent", actor=user, entity="user", entity_id=user["id"],
                  summary=f"Согласие на обработку ПДн: {user.get('full_name', '')} (политика от "
                          f"{fmt_version(POLICY_VERSION)})",
                  details={"policy_version": POLICY_VERSION, "at": ts}, db_path=db_path)
    return True, "Спасибо! Согласие сохранено."
